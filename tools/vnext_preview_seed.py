#!/usr/bin/env python3
"""Seed MOCK vnext_preview.building_images rows on a NON-production Neon branch.

The vNext serving projection (docs/vnext/BUILDING_IMAGES_DDL.sql) is not
deployed to production. This tool lets the archi-tinder backend develop
against the table shape early, on a dev branch, with clearly-labelled MOCK
data derived from existing canonical_v2_buildings columns:

  all_images[].url            -> one row per unique URL (sort_order 0..)
  covers_by_type{slot: url}   -> cover_slot / semantic_type / medium
  display_cover_url           -> is_cover_default (photograph rows only)

Nothing here is a real image classification (engine='mock_preview').

Safety:
  * --apply requires --dsn-env, and the DSN host must NOT be the production
    endpoint (ep-broad-hat-a1jaomn7); refused before connecting.
  * Dry-run is the default: read-only session, derive + check rows, no writes.
    Without --dsn-env a dry-run reads the make_db .env DB (production)
    read-only, which is how the derivation is validated against real data.
  * --apply runs in ONE transaction: CREATE SCHEMA IF NOT EXISTS, DDL
    (IF NOT EXISTS), TRUNCATE, batched INSERT, COMMENTs, COMMIT. Re-running is
    idempotent (truncate + reseed). Rows are validated by the Python mirror of
    every DDL constraint before anything is inserted.

Examples:
  .venv/Scripts/python.exe tools/vnext_preview_seed.py --limit 500             # dry-run vs prod, read-only
  .venv/Scripts/python.exe tools/vnext_preview_seed.py --dsn-env DEV_DATABASE_URL            # dry-run vs dev branch
  .venv/Scripts/python.exe tools/vnext_preview_seed.py --dsn-env DEV_DATABASE_URL --apply    # write MOCK rows to dev
  .venv/Scripts/python.exe tools/vnext_preview_seed.py --print-ddl
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Iterable, Iterator

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DDL_PATH = ROOT / "docs" / "vnext" / "BUILDING_IMAGES_DDL.sql"
PROD_ENDPOINT = "ep-broad-hat-a1jaomn7"
SCHEMA = "vnext_preview"
TABLE = "building_images"
INDEX_PREFIX = "vnext_preview_"
ENGINE = "mock_preview"
ENGINE_VERSION = "mock-0"
PROJECTION_VERSION = "mock-0"
SCHEMA_COMMENT = (
    "MOCK preview data for vNext building_images. Generated by tools/vnext_preview_seed.py "
    "(engine=mock_preview, engine_version=mock-0) from canonical_v2_buildings.all_images / "
    "covers_by_type / display_cover_url. NOT real image classification; non-production branch only."
)

# --- vocabularies: mirror docs/vnext/BUILDING_IMAGES_DDL.sql (tests assert equality) ---
SEMANTIC_TYPES = (
    "exterior_overall", "exterior_context", "interior", "threshold",
    "drawing", "rendering", "physical_model", "aerial", "detail",
    "construction_archive",
)
MEDIUMS = ("photograph", "drawing", "rendering", "physical_model", "mixed", "other", "unknown")
SPATIAL_CONTEXTS = ("exterior", "interior", "threshold", "unknown")
FRAMING_SCALES = ("site_context", "overall", "element_detail", "material_detail", "unknown")
CAMERA_ANGLES = ("eye_level", "elevated", "aerial_oblique", "aerial_top_down", "unknown")
DRAWING_KINDS = (
    "plan", "site_plan", "section", "elevation", "axonometric", "perspective",
    "detail", "diagram", "sketch", "composite", "other", "unknown",
)
PROJECT_STATES = (
    "visibly_finished", "construction_visible", "ruin_or_abandoned_visible",
    "demolition_visible", "unknown",
)
LEGIBILITIES = ("high", "medium", "low", "unknown")
COVER_SLOTS = ("exterior", "interior", "drawing", "aerial", "detail")
PHOTO_SLOTS = ("exterior", "interior", "aerial", "detail")
SLOT_TO_SEMANTIC = {"exterior": "exterior_overall", "interior": "interior", "aerial": "aerial", "detail": "detail"}

COLUMNS = (
    "canonical_bld_id", "image_asset_id", "url", "sort_order", "semantic_type", "medium",
    "spatial_context", "framing_scale", "camera_angle", "drawing_kind", "project_state",
    "project_legibility", "is_cover_default", "cover_slot", "engine", "engine_version",
    "projection_version",
)


# =========================================================================== safety

def dsn_host(dsn: str) -> str:
    """Best-effort host extraction from a URL or key=value DSN (no driver needed)."""
    m = re.match(r"^[a-z][a-z0-9+.-]*://(?:[^@/]*@)?([^/:?,]+)", dsn.strip(), re.I)
    if m:
        return m.group(1)
    m = re.search(r"(?:^|\s)host\s*=\s*'?([^\s']+)", dsn)
    return m.group(1) if m else ""


def is_production_dsn(dsn: str) -> bool:
    """True when the DSN points at production. Checks the parsed host AND the raw
    string (covers -pooler hosts, multi-host and options-style endpoint ids)."""
    return PROD_ENDPOINT in dsn_host(dsn).lower() or PROD_ENDPOINT in dsn.lower()


def refuse_if_production(dsn: str) -> None:
    if is_production_dsn(dsn):
        raise SystemExit(
            f"REFUSED: DSN targets the production endpoint ({PROD_ENDPOINT}). "
            "vnext_preview seeding is for non-production Neon branches only.")


# =========================================================================== DDL rewrite

def rewrite_ddl(ddl: str, schema: str = SCHEMA, index_prefix: str = INDEX_PREFIX) -> str:
    """Rewrite the WP0c DDL to <schema>.building_images.

    * table -> <schema>.building_images
    * FK    -> public.canonical_v2_buildings(canonical_bld_id)
    * index names prefixed with index_prefix, ON <schema>.building_images
    * CHECK clauses untouched (byte-identical)
    """
    out = re.sub(r"CREATE TABLE IF NOT EXISTS\s+building_images\b",
                 f"CREATE TABLE IF NOT EXISTS {schema}.{TABLE}", ddl)
    out = re.sub(r"REFERENCES\s+canonical_v2_buildings\s*\(",
                 "REFERENCES public.canonical_v2_buildings(", out)
    out = re.sub(r"(CREATE\s+(?:UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS\s+)(\w+)",
                 lambda m: m.group(1) + index_prefix + m.group(2), out)
    out = re.sub(r"\bON\s+building_images\b", f"ON {schema}.{TABLE}", out)
    leftover = re.findall(r"(?<![.\w])building_images\b(?!_)", _strip_sql_comments(out))
    if leftover:
        raise ValueError(f"unqualified building_images references remain: {len(leftover)}")
    return out


def _strip_sql_comments(sql: str) -> str:
    return re.sub(r"--[^\n]*", "", sql)


def extract_checks(sql: str) -> list[str]:
    """Return every CHECK (...) clause body with balanced parentheses."""
    sql = _strip_sql_comments(sql)
    out: list[str] = []
    for m in re.finditer(r"\bCHECK\s*\(", sql):
        depth, i = 1, m.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(sql[i], 0)
            i += 1
        out.append(sql[m.end(): i - 1])
    return out


# =========================================================================== derivation

def asset_id(url: str) -> str:
    return hashlib.sha1(url.encode("utf-8")).hexdigest()[:16]


def _as_obj(v: Any) -> Any:
    return json.loads(v) if isinstance(v, str) else v


def derive_rows(building: dict[str, Any], stats: Counter | None = None) -> list[dict[str, Any]]:
    """Derive MOCK building_images rows for one building.

    building keys: canonical_bld_id, all_images (list of {url,...}),
    covers_by_type ({slot: url|None}), display_cover_url.
    """
    stats = stats if stats is not None else Counter()
    bld = building["canonical_bld_id"]
    images = _as_obj(building.get("all_images")) or []
    covers = _as_obj(building.get("covers_by_type")) or {}
    display = building.get("display_cover_url") or None

    urls: list[str] = []
    seen: set[str] = set()
    for img in images:
        url = img.get("url") if isinstance(img, dict) else None
        if not isinstance(url, str) or not url.strip(" "):
            stats["skipped_blank_url"] += 1
            continue
        if url in seen:
            stats["skipped_duplicate_url"] += 1
            continue
        seen.add(url)
        urls.append(url)

    slots_by_url: dict[str, set[str]] = {}
    for slot in COVER_SLOTS:  # deterministic order; unknown slot keys ignored
        url = covers.get(slot)
        if isinstance(url, str) and url.strip(" "):
            slots_by_url.setdefault(url, set()).add(slot)
    for key in covers:
        if key not in COVER_SLOTS and covers[key]:
            stats["ignored_unknown_cover_key"] += 1

    # Cover URLs (often an alternate rendition) absent from all_images are appended
    # so the slot/default exists in the preview.
    for slot in COVER_SLOTS:
        url = covers.get(slot)
        if isinstance(url, str) and url.strip(" ") and url not in seen:
            seen.add(url)
            urls.append(url)
            stats["appended_cover_url_not_in_all_images"] += 1
    if display and display.strip(" ") and display not in seen:
        seen.add(display)
        urls.append(display)
        stats["appended_display_cover_not_in_all_images"] += 1

    rows: list[dict[str, Any]] = []
    used_ids: set[str] = set()
    for url in urls:
        aid = asset_id(url)
        if aid in used_ids:  # sha1[:16] collision inside one building
            stats["skipped_asset_id_collision"] += 1
            continue
        used_ids.add(aid)
        slots = slots_by_url.get(url, set())
        row: dict[str, Any] = {
            "canonical_bld_id": bld, "image_asset_id": aid, "url": url,
            "sort_order": len(rows), "project_legibility": "unknown",
            "engine": ENGINE, "engine_version": ENGINE_VERSION, "projection_version": PROJECTION_VERSION,
        }
        if "drawing" in slots:
            if slots & set(PHOTO_SLOTS):
                stats["dropped_photo_slots_on_drawing"] += 1  # drawing wins (DDL forbids mixing)
            row.update(semantic_type=["drawing"], medium="drawing", spatial_context=None,
                       framing_scale=None, camera_angle=None, drawing_kind="unknown",
                       project_state=None, is_cover_default=False, cover_slot=["drawing"])
            if url == display:
                stats["display_cover_is_drawing_no_default"] += 1
        else:
            photo_slots = [s for s in PHOTO_SLOTS if s in slots]
            semantic = [t for t in SEMANTIC_TYPES if t in {SLOT_TO_SEMANTIC[s] for s in photo_slots}]
            row.update(semantic_type=semantic or ["exterior_overall"], medium="photograph",
                       spatial_context="unknown", framing_scale="unknown", camera_angle="unknown",
                       drawing_kind=None, project_state="unknown",
                       is_cover_default=(url == display),
                       cover_slot=[s for s in COVER_SLOTS if s in photo_slots])
        rows.append(row)
        stats["rows"] += 1
        stats[f"medium:{row['medium']}"] += 1
        for s in row["cover_slot"]:
            stats[f"cover_slot:{s}"] += 1
        stats["is_cover_default"] += int(row["is_cover_default"])
    stats["buildings"] += 1
    if not any(r["is_cover_default"] for r in rows):
        stats["buildings_without_default_cover"] += 1
    return rows


# =========================================================================== constraint checker

def _nonblank(v: Any) -> bool:
    # Postgres trim() strips spaces only.
    return isinstance(v, str) and len(v.strip(" ")) > 0


def _tv_in(v: Any, vocab: Iterable[str]) -> bool | None:
    return None if v is None else v in vocab


def _tv_or(a: bool | None, b: bool | None) -> bool | None:
    if a is True or b is True:
        return True
    if a is None or b is None:
        return None
    return False


def check_row(r: dict[str, Any]) -> list[str]:
    """Mirror of every column/table CHECK + NOT NULL in BUILDING_IMAGES_DDL.sql.
    SQL three-valued logic: a CHECK fails only when it evaluates to FALSE."""
    errs: list[str] = []
    for col in ("canonical_bld_id", "image_asset_id", "url", "sort_order", "semantic_type", "medium",
                "project_legibility", "is_cover_default", "cover_slot", "engine", "engine_version",
                "projection_version"):
        if r.get(col) is None:
            errs.append(f"not_null:{col}")
    if errs:
        return errs
    for col in ("image_asset_id", "url", "engine", "engine_version", "projection_version"):
        if not _nonblank(r[col]):
            errs.append(f"check_nonblank:{col}")
    if not isinstance(r["sort_order"], int) or isinstance(r["sort_order"], bool) or r["sort_order"] < 0:
        errs.append("check_sort_order")
    st, cs = r["semantic_type"], r["cover_slot"]
    if not isinstance(st, list) or len(st) < 1 or any(x is None or x not in SEMANTIC_TYPES for x in st):
        errs.append("check_semantic_type")
    if not isinstance(cs, list) or any(x is None or x not in COVER_SLOTS for x in cs):
        errs.append("check_cover_slot")
        cs = [x for x in cs or [] if x]
    if r["medium"] not in MEDIUMS:
        errs.append("check_medium")
    for col, vocab in (("spatial_context", SPATIAL_CONTEXTS), ("framing_scale", FRAMING_SCALES),
                       ("camera_angle", CAMERA_ANGLES), ("drawing_kind", DRAWING_KINDS),
                       ("project_state", PROJECT_STATES)):
        if _tv_in(r.get(col), vocab) is False:
            errs.append(f"check_{col}")
    if r["project_legibility"] not in LEGIBILITIES:
        errs.append("check_project_legibility")
    if not isinstance(r["is_cover_default"], bool):
        errs.append("type_is_cover_default")

    m = r["medium"]
    nn = {c: r.get(c) is not None for c in ("spatial_context", "framing_scale", "camera_angle", "drawing_kind", "project_state")}
    shape_ok = (
        (m == "photograph" and nn["spatial_context"] and nn["framing_scale"] and nn["camera_angle"]
         and not nn["drawing_kind"] and nn["project_state"])
        or (m == "drawing" and not nn["spatial_context"] and not nn["framing_scale"] and not nn["camera_angle"]
            and nn["drawing_kind"] and not nn["project_state"])
        or (m == "rendering" and nn["spatial_context"] and nn["framing_scale"] and nn["camera_angle"]
            and nn["drawing_kind"] and not nn["project_state"])
        or (m in ("physical_model", "mixed", "other", "unknown") and not any(nn.values()))
    )
    if not shape_ok:
        errs.append("check_medium_field_shape")
    cam = r.get("camera_angle")
    aerial_ok = _tv_or(None if cam is None else cam not in ("aerial_oblique", "aerial_top_down"),
                       _tv_in(r.get("spatial_context"), ("exterior", "unknown")))
    if aerial_ok is False:
        errs.append("check_aerial_camera_spatial")
    if r["is_cover_default"] and m != "photograph":
        errs.append("check_cover_default_photograph")
    if set(cs) & set(PHOTO_SLOTS) and m != "photograph":
        errs.append("check_photo_slot_photograph")
    if "drawing" in cs and m != "drawing":
        errs.append("check_drawing_slot_drawing")
    return errs


def check_rows(rows: Iterable[dict[str, Any]], known_bld_ids: set[str] | None = None) -> Counter:
    """Row checks + PK, UNIQUE(bld, sort_order), the 6 partial unique indexes and
    (optionally) the FK. Returns Counter of violation codes (empty == pass)."""
    v: Counter = Counter()
    pk: set[tuple] = set()
    order: set[tuple] = set()
    default: set[str] = set()
    slot_seen: dict[str, set[str]] = {s: set() for s in COVER_SLOTS}
    for r in rows:
        for e in check_row(r):
            v[e] += 1
        bld = r.get("canonical_bld_id")
        if known_bld_ids is not None and bld not in known_bld_ids:
            v["fk_canonical_bld_id"] += 1
        key = (bld, r.get("image_asset_id"))
        if key in pk:
            v["pk_duplicate"] += 1
        pk.add(key)
        key = (bld, r.get("sort_order"))
        if key in order:
            v["unique_sort_order"] += 1
        order.add(key)
        if r.get("is_cover_default"):
            if bld in default:
                v["uq_default_cover"] += 1
            default.add(bld)
        for s in set(r.get("cover_slot") or []):
            if s in slot_seen:
                if bld in slot_seen[s]:
                    v[f"uq_{s}_cover"] += 1
                slot_seen[s].add(bld)
    return v


# =========================================================================== DB I/O

SOURCE_SQL = """
SELECT canonical_bld_id, all_images, covers_by_type, display_cover_url
  FROM public.canonical_v2_buildings
 WHERE is_publishable
 ORDER BY canonical_bld_id
"""


def _connect(dsn_env: str | None, readonly: bool):
    import psycopg2

    try:
        from dotenv import load_dotenv

        load_dotenv(ROOT / ".env")
    except ImportError:  # pragma: no cover
        pass
    if dsn_env:
        dsn = os.environ.get(dsn_env)
        if not dsn:
            raise SystemExit(f"env var {dsn_env} is not set (value never printed)")
        if not readonly:
            refuse_if_production(dsn)
        conn = psycopg2.connect(dsn)
    else:
        if not readonly:
            raise SystemExit("REFUSED: --apply requires --dsn-env pointing at a non-production branch")
        from tools.canonical_v2_neon_loader import _connect as prod_connect

        conn = prod_connect()
    # Belt-and-braces: verify the server-reported host too.
    host = (getattr(conn, "info", None) and conn.info.host) or ""
    if not readonly and PROD_ENDPOINT in host.lower():
        conn.close()
        raise SystemExit(f"REFUSED: connected host is the production endpoint ({PROD_ENDPOINT})")
    if readonly:
        conn.set_session(readonly=True, autocommit=False)
        with conn.cursor() as cur:
            cur.execute("SET default_transaction_read_only = on")
    return conn


def iter_buildings(conn, limit: int | None, batch: int) -> Iterator[dict[str, Any]]:
    sql = SOURCE_SQL + (" LIMIT %s" % int(limit) if limit else "")
    with conn.cursor(name="vnext_preview_src") as cur:
        cur.itersize = batch
        cur.execute(sql)
        for bld, images, covers, display in cur:
            yield {"canonical_bld_id": bld, "all_images": images, "covers_by_type": covers,
                   "display_cover_url": display}


def _row_tuple(r: dict[str, Any]) -> tuple:
    return tuple(r[c] for c in COLUMNS)


def run(dsn_env: str | None, apply: bool, limit: int | None, batch: int) -> dict[str, Any]:
    ddl = rewrite_ddl(DDL_PATH.read_text(encoding="utf-8"))
    conn = _connect(dsn_env, readonly=not apply)
    stats: Counter = Counter()
    try:
        # Pass 1 (stream: read + derive + check). Every constraint is scoped to one
        # building, so violations are accumulated per building without holding rows.
        violations: Counter = Counter()
        for b in iter_buildings(conn, limit, batch):
            violations.update(check_rows(derive_rows(b, stats), {b["canonical_bld_id"]}))
        result = {
            "mode": "apply" if apply else "dry-run",
            "source": f"db:{dsn_env or 'make_db .env (read-only)'}",
            "limit": limit,
            "stats": dict(sorted(stats.items())),
            "violations": dict(violations),
            "checker": "PASS" if not violations else "FAIL",
        }
        if not apply:
            conn.rollback()
            return result
        if violations:
            conn.rollback()
            raise SystemExit("REFUSED: derived rows violate DDL constraints: " + json.dumps(dict(violations)))

        # Pass 2 (same transaction): DDL, truncate, re-derive and batch insert.
        from psycopg2.extras import execute_values

        with conn.cursor() as cur:
            cur.execute(f"CREATE SCHEMA IF NOT EXISTS {SCHEMA}")
            cur.execute(ddl)
            cur.execute(f"TRUNCATE {SCHEMA}.{TABLE}")
            insert = f"INSERT INTO {SCHEMA}.{TABLE} ({', '.join(COLUMNS)}) VALUES %s"
            buf: list[tuple] = []
            for b in iter_buildings(conn, limit, batch):
                buf.extend(_row_tuple(r) for r in derive_rows(b, Counter()))
                if len(buf) >= batch:
                    execute_values(cur, insert, buf, page_size=batch)
                    buf = []
            if buf:
                execute_values(cur, insert, buf, page_size=batch)
            cur.execute(f"COMMENT ON SCHEMA {SCHEMA} IS %s", (SCHEMA_COMMENT,))
            cur.execute(f"COMMENT ON TABLE {SCHEMA}.{TABLE} IS %s", ("MOCK rows (engine=mock_preview). " + SCHEMA_COMMENT,))
            # the app's read-only role (make_web) must see the preview like it sees public
            cur.execute("SELECT 1 FROM pg_roles WHERE rolname = 'make_web'")
            if cur.fetchone():
                cur.execute(f"GRANT USAGE ON SCHEMA {SCHEMA} TO make_web")
                cur.execute(f"GRANT SELECT ON ALL TABLES IN SCHEMA {SCHEMA} TO make_web")
            cur.execute(f"SELECT count(*) FROM {SCHEMA}.{TABLE}")
            result["inserted"] = cur.fetchone()[0]
            if result["inserted"] != stats["rows"]:
                raise RuntimeError(f"inserted {result['inserted']} != derived {stats['rows']}; rolled back")
        conn.commit()
        return result
    except BaseException:
        conn.rollback()
        raise
    finally:
        conn.close()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dsn-env", help="env var holding a NON-production postgres URL")
    ap.add_argument("--apply", action="store_true", help="write (default is read-only dry-run)")
    ap.add_argument("--limit", type=int, help="only the first N publishable buildings (by id)")
    ap.add_argument("--batch", type=int, default=500, help="fetch/insert batch size")
    ap.add_argument("--print-ddl", action="store_true", help="print the rewritten DDL and exit")
    args = ap.parse_args(argv)
    if args.print_ddl:
        print(rewrite_ddl(DDL_PATH.read_text(encoding="utf-8")))
        return 0
    if args.apply and not args.dsn_env:
        raise SystemExit("REFUSED: --apply requires --dsn-env pointing at a non-production branch")
    result = run(args.dsn_env, args.apply, args.limit, args.batch)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0 if result["checker"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
